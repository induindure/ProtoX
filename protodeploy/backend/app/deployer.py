import re, secrets, shutil, subprocess, tempfile
from pathlib import Path
import requests
from .detector import detect_stack
from .templates import PAGES_WORKFLOW, GITIGNORE, render_yaml
from .patch import patch_router_basename, patch_requirements, patch_vue_config

GH = "https://api.github.com"

def _h(token: str) -> dict:
    return {"Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28"}

def _run(cmd: list, cwd: Path, token: str) -> str:
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError((r.stderr or r.stdout).replace(token, "***"))
    return r.stdout

def deploy_to_github(project_dir: Path, token: str, repo_name: str) -> dict:
    repo = re.sub(r"[^a-zA-Z0-9._-]", "-", repo_name).strip("-").lower() or "protox-app"

    me = requests.get(f"{GH}/user", headers=_h(token))
    if me.status_code != 200:
        raise RuntimeError("Invalid GitHub token")
    owner = me.json()["login"]

    # 1. Copy project (never copy node_modules / .git)
    work = Path(tempfile.mkdtemp()) / "app"
    shutil.copytree(project_dir, work, ignore=shutil.ignore_patterns(
        "node_modules", ".git", "venv", ".venv", "__pycache__", "dist"))

    # 1b. Patch the copy so it works on GitHub Pages / Render
    patched = patch_router_basename(work)
    patched += patch_requirements(work)
    patched += patch_vue_config(work)

    # 2. Create repo (retry with suffix if name is taken)
    for _ in range(3):
        r = requests.post(f"{GH}/user/repos", headers=_h(token), json={
            "name": repo, "private": False,
            "description": "Generated and deployed by ProtoX"})
        if r.status_code == 201:
            break
        if r.status_code == 422:
            repo = f"{repo}-{secrets.token_hex(2)}"
            continue
        raise RuntimeError(f"Repo creation failed: {r.text}")
    else:
        raise RuntimeError("Could not find a free repo name")

    # 3. Inject deployment files
    stack = detect_stack(work)
    api_name = f"{repo}-api-{secrets.token_hex(2)}"[:60]
    api_url = f"https://{api_name}.onrender.com"

    wf = work / ".github" / "workflows"
    wf.mkdir(parents=True, exist_ok=True)
    (wf / "deploy-frontend.yml").write_text(
        PAGES_WORKFLOW.replace("__REPO__", repo).replace("__API_URL__", api_url))
    (work / "render.yaml").write_text(render_yaml(stack, api_name, owner))
    (work / ".gitignore").write_text(GITIGNORE)

    # 4. Enable Pages (GitHub Actions source) BEFORE first push
    p = requests.post(f"{GH}/repos/{owner}/{repo}/pages", headers=_h(token),
                      json={"build_type": "workflow"})
    if p.status_code not in (201, 409):
        raise RuntimeError(f"Enabling Pages failed: {p.text}")

    # 5. Push
    _run(["git", "init", "-b", "main"], work, token)
    _run(["git", "config", "user.name", "ProtoX"], work, token)
    _run(["git", "config", "user.email", "protox@users.noreply.github.com"], work, token)
    _run(["git", "add", "-A"], work, token)
    _run(["git", "commit", "-m", "Initial commit: generated by ProtoX"], work, token)
    _run(["git", "push", f"https://{owner}:{token}@github.com/{owner}/{repo}.git", "main"],
         work, token)
    shutil.rmtree(work.parent, ignore_errors=True)

    repo_url = f"https://github.com/{owner}/{repo}"
    return {
        "owner": owner, "repo": repo, "stack": stack,
        "patched": patched,
        "repo_url": repo_url,
        "frontend_url": f"https://{owner}.github.io/{repo}/",
        "backend_deploy_url": f"https://render.com/deploy?repo={repo_url}",
        "backend_url": api_url,
        "actions_url": f"{repo_url}/actions",
    }